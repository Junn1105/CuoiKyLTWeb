package vn.mocsach.catalog;
import org.junit.jupiter.api.*;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.jdbc.JdbcTest;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.web.server.ResponseStatusException;
import vn.mocsach.auth.AuthProblem;
import static org.junit.jupiter.api.Assertions.*;
@JdbcTest @Import({CatalogService.class,BookDetailService.class})
class BookDetailServiceTest {
 @Autowired JdbcTemplate jdbc;@Autowired BookDetailService service;
 @BeforeEach void setup(){
  jdbc.execute("CREATE SCHEMA IF NOT EXISTS dbo");
  for(String sql:new String[]{
   "CREATE TABLE dbo.Categories(CategoryId int,CategoryName nvarchar(100))",
   "CREATE TABLE dbo.Publishers(PublisherId int,PublisherName nvarchar(100))",
   "CREATE TABLE dbo.Books(BookId int,Title nvarchar(255),CoverImage nvarchar(255),CategoryId int,ISBN varchar(20),PublisherId int,PublishYear int,Translator nvarchar(250),Description nvarchar(2000))",
   "CREATE TABLE dbo.Authors(AuthorId int,AuthorName nvarchar(150))",
   "CREATE TABLE dbo.BookAuthors(BookId int,AuthorId int)",
   "CREATE TABLE dbo.Users(UserId int,FullName nvarchar(150),Status varchar(20))",
   "CREATE TABLE dbo.BookReviews(ReviewId bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,BookId int,UserId int,Rating int,Comment nvarchar(2000),Status varchar(20),CreatedAt timestamp,UNIQUE(UserId,BookId))",
   "CREATE TABLE dbo.BookCopies(CopyId int,BookId int,Status varchar(20),SalePrice decimal(19,2))",
   "CREATE TABLE dbo.Orders(OrderId int,Status varchar(20))",
   "CREATE TABLE dbo.OrderItems(OrderItemId int,OrderId int,CopyId int)",
   "CREATE TABLE dbo.SalesReturns(ReturnId int,Status varchar(20))",
   "CREATE TABLE dbo.SalesReturnItems(ReturnId int,OrderItemId int,Status varchar(20))"
  })jdbc.execute(sql.replace("CREATE TABLE ","CREATE TABLE IF NOT EXISTS "));
  for(String name:new String[]{"SalesReturnItems","SalesReturns","OrderItems","Orders","BookCopies","BookReviews","BookAuthors","Authors","Books","Categories","Publishers","Users"})jdbc.update("DELETE FROM dbo."+name);
  jdbc.update("INSERT INTO dbo.Categories VALUES(1,'Văn học')");jdbc.update("INSERT INTO dbo.Publishers VALUES(1,'NXB Trẻ')");
  jdbc.update("INSERT INTO dbo.Books VALUES(1,'Sách A',NULL,1,'123',1,2020,NULL,'Mô tả A'),(2,'Sách B',NULL,1,NULL,NULL,NULL,NULL,NULL),(3,'Sách C',NULL,1,NULL,1,2021,'Người dịch',NULL)");
  jdbc.update("INSERT INTO dbo.Authors VALUES(1,'Tác giả A'),(2,'Tác giả B')");jdbc.update("INSERT INTO dbo.BookAuthors VALUES(1,1),(1,2),(2,1),(2,2),(3,2)");
  jdbc.update("INSERT INTO dbo.Users VALUES(1,'Bạn đọc','ACTIVE'),(2,'Bạn khác','ACTIVE'),(3,'Bị khóa','LOCKED')");
  jdbc.update("INSERT INTO dbo.BookCopies VALUES(1,1,'AVAILABLE',80000),(2,1,'SOLD',90000)");
 }
 @Test void detailsUseRealMetadataAndDeduplicateSharedAuthors(){
  var book=service.detail(1);assertEquals("NXB Trẻ",book.get("publisher"));assertEquals("Đang cập nhật",book.get("translator"));assertEquals("Mô tả A",book.get("description"));
  var related=(java.util.List<?>)book.get("related");assertEquals(2,related.size());assertEquals(1,((Number)book.get("available")).intValue());
  assertEquals("Tạm hết hàng",service.detail(2).get("priceLabel"));assertThrows(ResponseStatusException.class,()->service.detail(999));
 }
 @Test void publicReviewsAndHistogramExcludePendingAndHidden(){
  jdbc.update("INSERT INTO dbo.BookReviews(BookId,UserId,Rating,Comment,Status,CreatedAt) VALUES(1,1,5,'Hay','APPROVED',CURRENT_TIMESTAMP),(1,2,1,'Chờ','PENDING',CURRENT_TIMESTAMP),(1,3,2,'Ẩn','HIDDEN',CURRENT_TIMESTAMP)");
  assertEquals(1,service.reviews(1).size());assertEquals(100L,service.histogram(1).get(0).get("percent"));assertEquals(0L,service.histogram(2).get(0).get("percent"));
 }
 @Test void authenticatedReviewIsPublishedAndEditsDoNotDuplicate(){
  service.review(1,1,5,"Sách rất hay");assertEquals("APPROVED",service.ownReview(1,1).get("status"));assertEquals(1,service.reviews(1).size());
  service.review(1,1,4,"Cảm nhận cập nhật");assertEquals(1,jdbc.queryForObject("SELECT COUNT(*) FROM dbo.BookReviews",Integer.class));assertEquals(4,service.ownReview(1,1).get("rating"));
 }
 @Test void invalidRatingsCommentsMissingBookAndLockedUsersAreRejected(){
  assertThrows(AuthProblem.class,()->service.review(1,1,6,"Hay quá"));assertThrows(AuthProblem.class,()->service.review(1,1,5,"a"));assertThrows(AuthProblem.class,()->service.review(1,1,5,"a".repeat(2001)));assertThrows(AuthProblem.class,()->service.review(1,3,5,"Hay quá"));assertThrows(ResponseStatusException.class,()->service.review(999,1,5,"Hay quá"));
  service.review(1,1,5,"Sách rất hay");jdbc.update("UPDATE dbo.BookReviews SET Status='HIDDEN'");assertThrows(AuthProblem.class,()->service.review(1,1,4,"Muốn sửa lại"));
 }
}
