 @Test void placesQrOrderConfirmsPaymentAndAllowsCancellationRestoringStock() {
  cart.add(1, 1, 1);
  var shipping = checkout.validateAndSaveShipping(1, "Nguyễn Phước Sang", "0901234567", "Quận 3, TP.HCM", "120 Kỳ Đồng", "Giao giờ hành chính");
  assertEquals("0901234567", checkout.defaultShippingInfo(1).get("recipientPhone"));

  int orderId = checkout.placeOrder(1, shipping, "BANK_TRANSFER");
  assertEquals(0, cart.count(1));
  assertEquals("RESERVED", jdbc.queryForObject("SELECT Status FROM dbo.BookCopies WHERE CopyId=10", String.class));

  var detail = checkout.orderDetail(1, orderId);
  assertEquals("PENDING", detail.get("status"));
  assertEquals(0, new BigDecimal("80000").compareTo((BigDecimal) detail.get("totalAmount")));
  @SuppressWarnings("unchecked")
  var payment = (Map<String, Object>) detail.get("payment");
  assertEquals("BANK_TRANSFER", payment.get("method"));
  assertEquals(false, payment.get("isPaid"));

  // Staff (userId = 99) can view & print invoice of customer's order
  var staffInvoiceView = checkout.orderDetail(99, orderId);
  assertEquals(detail.get("orderCode"), staffInvoiceView.get("orderCode"));

  var confirmed = checkout.confirmQrPayment(1, orderId);
  assertEquals("CONFIRMED", confirmed.get("status"));
  @SuppressWarnings("unchecked")
  var confirmedPayment = (Map<String, Object>) confirmed.get("payment");
  assertEquals(true, confirmedPayment.get("isPaid"));

  var cancelled = checkout.cancelOrder(1, orderId);
  assertEquals("CANCELLED", cancelled.get("status"));
  assertEquals("AVAILABLE", jdbc.queryForObject("SELECT Status FROM dbo.BookCopies WHERE CopyId=10", String.class));
  assertThrows(AuthProblem.class, () -> checkout.cancelOrder(1, orderId));
 }
 @Test void testMultiBranchCheckoutCreatesSeparateSubOrdersPerBranchWithSingleShippingFee() {
  jdbc.update("INSERT INTO dbo.Stores VALUES(2,'Chi nhánh Thủ Đức','1 Võ Văn Ngân, Thủ Đức','02838887777','ACTIVE')");
  jdbc.update("INSERT INTO dbo.Stores VALUES(3,'Chi nhánh Bình Thạnh','10 Bạch Đằng, Bình Thạnh','02838886666','ACTIVE')");
  jdbc.update("INSERT INTO dbo.Books VALUES(2,'Chí Phèo','/images/books/chi-pheo.jpg',1)");
  jdbc.update("INSERT INTO dbo.Books VALUES(3,'Tắt Đèn','/images/books/tat-den.jpg',1)");

  // 3 copies at 3 different stores
  // Copy 10 is already at Store 1 (SalePrice 55,000)
  jdbc.update("INSERT INTO dbo.BookCopies(CopyId,CopyCode,BookId,StoreId,ConditionId,Status,CostPrice,SalePrice,ConditionNotes,Version,UpdatedAt) VALUES(20,'C2-020',2,2,1,'AVAILABLE',25000,45000,'Tốt',0,CURRENT_TIMESTAMP)");
  jdbc.update("INSERT INTO dbo.BookCopies(CopyId,CopyCode,BookId,StoreId,ConditionId,Status,CostPrice,SalePrice,ConditionNotes,Version,UpdatedAt) VALUES(30,'C3-030',3,3,1,'AVAILABLE',35000,60000,'Đẹp',0,CURRENT_TIMESTAMP)");

  cart.add(1, 1, 1); // Book 1 at Store 1
  cart.add(1, 2, 1); // Book 2 at Store 2
  cart.add(1, 3, 1); // Book 3 at Store 3
  assertEquals(3, cart.count(1));

  var shipping = checkout.validateAndSaveShipping(1, "Nguyễn Phước Sang", "0901234567", "Quận 3, TP.HCM", "120 Kỳ Đồng", "Giao 3 cuốn sách");
  int firstOrderId = checkout.placeOrder(1, shipping, "BANK_TRANSFER");

  assertEquals(0, cart.count(1));
  assertEquals("RESERVED", jdbc.queryForObject("SELECT Status FROM dbo.BookCopies WHERE CopyId=10", String.class));
  assertEquals("RESERVED", jdbc.queryForObject("SELECT Status FROM dbo.BookCopies WHERE CopyId=20", String.class));
  assertEquals("RESERVED", jdbc.queryForObject("SELECT Status FROM dbo.BookCopies WHERE CopyId=30", String.class));

  Integer totalOrders = jdbc.queryForObject("SELECT COUNT(*) FROM dbo.Orders WHERE CustomerId=1", Integer.class);
  assertEquals(3, totalOrders);

  // Each branch has exactly 1 order
  assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM dbo.Orders WHERE StoreId=1", Integer.class));
  assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM dbo.Orders WHERE StoreId=2", Integer.class));
  assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM dbo.Orders WHERE StoreId=3", Integer.class));

  // Check shipping fee distribution: only first store has 25k shipping fee
  BigDecimal fee1 = jdbc.queryForObject("SELECT ShippingFee FROM dbo.Orders WHERE StoreId=1", BigDecimal.class);
  BigDecimal fee2 = jdbc.queryForObject("SELECT ShippingFee FROM dbo.Orders WHERE StoreId=2", BigDecimal.class);
  BigDecimal fee3 = jdbc.queryForObject("SELECT ShippingFee FROM dbo.Orders WHERE StoreId=3", BigDecimal.class);
  assertEquals(0, new BigDecimal("25000").compareTo(fee1));
  assertEquals(0, BigDecimal.ZERO.compareTo(fee2));
  assertEquals(0, BigDecimal.ZERO.compareTo(fee3));

  // Total customer payment = (55k + 45k + 60k) + 25k = 185,000 VND
  BigDecimal sumTotal = jdbc.queryForObject("SELECT SUM(TotalAmount) FROM dbo.Orders WHERE CustomerId=1", BigDecimal.class);
  assertEquals(0, new BigDecimal("185000").compareTo(sumTotal));

  // Verify orderDetail aggregates multi-store sibling orders
  var detail = checkout.orderDetail(1, firstOrderId);
  assertTrue(Boolean.TRUE.equals(detail.get("isMultiStore")));
  @SuppressWarnings("unchecked")
  var siblings = (java.util.List<Map<String, Object>>) detail.get("siblingOrders");
  assertEquals(3, siblings.size());
  assertEquals(0, new BigDecimal("185000").compareTo((BigDecimal) detail.get("groupTotalAmount")));

  // Verify confirmQrPayment confirms all 3 sub-orders and marks payments SUCCEEDED
  var confirmed = checkout.confirmQrPayment(1, firstOrderId);
  assertEquals("CONFIRMED", confirmed.get("status"));

  var statuses = jdbc.queryForList("SELECT Status FROM dbo.Orders WHERE CustomerId=1", String.class);
  assertEquals(3, statuses.size());
  assertTrue(statuses.stream().allMatch("CONFIRMED"::equals));

  var paymentStatuses = jdbc.queryForList("SELECT Status FROM dbo.Payments", String.class);
  assertEquals(3, paymentStatuses.size());
  assertTrue(paymentStatuses.stream().allMatch("SUCCEEDED"::equals));
 }

 @Test void testOrderTimeoutAutoCancelsAndRestoresStock() {
  cart.add(1, 1, 1);
  var shipping = checkout.validateAndSaveShipping(1, "Nguyễn Phước Sang", "0901234567", "Quận 3, TP.HCM", "120 Kỳ Đồng", "Giao hàng");
  int orderId = checkout.placeOrder(1, shipping, "BANK_TRANSFER");

  assertEquals("RESERVED", jdbc.queryForObject("SELECT Status FROM dbo.BookCopies WHERE CopyId=10", String.class));
  var detail = checkout.orderDetail(1, orderId);
  assertEquals("PENDING", detail.get("status"));
  assertEquals(true, detail.get("hasWaitingTimer"));
  assertEquals(15, detail.get("waitingMinutes"));
  assertTrue(((Number) detail.get("remainingSeconds")).longValue() > 0);

  // Age the order by 20 minutes (exceeding 15-minute wait time)
  java.sql.Timestamp pastTime = new java.sql.Timestamp(System.currentTimeMillis() - 20 * 60 * 1000L);
  jdbc.update("UPDATE dbo.Orders SET CreatedAt=? WHERE OrderId=?", pastTime, orderId);

  // Trigger auto-cancellation
  int cancelled = checkout.cancelExpiredPendingOrders();
  assertEquals(1, cancelled);

  // Verify status is CANCELLED and book copy restored to AVAILABLE
  assertEquals("CANCELLED", jdbc.queryForObject("SELECT Status FROM dbo.Orders WHERE OrderId=?", String.class, orderId));
  assertEquals("CANCELLED", jdbc.queryForObject("SELECT Status FROM dbo.Payments WHERE OrderId=?", String.class, orderId));
  assertEquals("AVAILABLE", jdbc.queryForObject("SELECT Status FROM dbo.BookCopies WHERE CopyId=10", String.class));

  var afterCancel = checkout.orderDetail(1, orderId);
  assertEquals("CANCELLED", afterCancel.get("status"));
  assertEquals(true, afterCancel.get("isExpired"));

  // Verify user notification was created
  Integer notifCount = jdbc.queryForObject("SELECT COUNT(*) FROM dbo.Notifications WHERE UserId=1 AND Type='ORDER'", Integer.class);
  assertNotNull(notifCount);
  assertTrue(notifCount > 0);
 }

 @Test void testCustomerConfirmsOrderReceivedTransitionsToCompleted() {
  cart.add(1, 1, 1);
  var shipping = checkout.validateAndSaveShipping(1, "Nguyễn Phước Sang", "0901234567", "Quận 3, TP.HCM", "120 Kỳ Đồng", "Giao hàng");
  int orderId = checkout.placeOrder(1, shipping, "CASH");

  var detail = checkout.orderDetail(1, orderId);
  assertEquals("PENDING", detail.get("status"));
  assertEquals(false, detail.get("canConfirmReceived"));
  assertThrows(AuthProblem.class, () -> checkout.confirmOrderReceived(1, orderId));

  // Chuyển sang SHIPPED (Đang giao hàng) thì mới có nút Đã nhận hàng
  jdbc.update("UPDATE dbo.Orders SET Status='SHIPPED' WHERE OrderId=?", orderId);
  var shippedDetail = checkout.orderDetail(1, orderId);
  assertEquals("SHIPPED", shippedDetail.get("status"));
  assertEquals(true, shippedDetail.get("canConfirmReceived"));

  // Customer clicks "Đã nhận hàng"
  var completed = checkout.confirmOrderReceived(1, orderId);
  assertEquals("COMPLETED", completed.get("status"));
  assertEquals("Đã giao thành công", completed.get("statusLabel"));
  assertEquals(false, completed.get("canConfirmReceived"));

  // Sách chuyển sang SOLD
  assertEquals("SOLD", jdbc.queryForObject("SELECT Status FROM dbo.BookCopies WHERE CopyId=10", String.class));
  // Thanh toán chuyển sang SUCCEEDED
  assertEquals("SUCCEEDED", jdbc.queryForObject("SELECT Status FROM dbo.Payments WHERE OrderId=?", String.class, orderId));

  // Thử xác nhận lại sẽ báo lỗi
  assertThrows(AuthProblem.class, () -> checkout.confirmOrderReceived(1, orderId));
 }

 @Test void testCheckQrStatusPollingScenarios() {
  cart.add(1, 1, 1);
  var shipping = checkout.validateAndSaveShipping(1, "Nguyễn Phước Sang", "0901234567", "Quận 3, TP.HCM", "120 Kỳ Đồng", "Giao hàng");
  int orderId = checkout.placeOrder(1, shipping, "BANK_TRANSFER");

  // 1. Khi đơn vừa tạo, trạng thái PENDING và chưa thanh toán
  var statusPending = checkout.checkQrStatus(1, orderId);
  assertEquals("PENDING", statusPending.get("status"));
  assertEquals(false, statusPending.get("shouldRedirect"));
  assertEquals(false, statusPending.get("isPaid"));
  assertEquals(false, statusPending.get("isCancelled"));

  // 2. Staff cập nhật đơn sang 'PROCESSING' (Đang chuẩn bị hàng)
  jdbc.update("UPDATE dbo.Orders SET Status='PROCESSING' WHERE OrderId=?", orderId);
  var statusProcessing = checkout.checkQrStatus(1, orderId);
  assertEquals("PROCESSING", statusProcessing.get("status"));
  assertEquals("Đang chuẩn bị hàng", statusProcessing.get("statusLabel"));
  assertEquals(true, statusProcessing.get("shouldRedirect"));
  assertEquals(true, statusProcessing.get("isPaid"));
  assertEquals("SUCCEEDED", statusProcessing.get("paymentStatus"));
  // Kiểm tra bảng Payments đã được cập nhật sang SUCCEEDED
  assertEquals("SUCCEEDED", jdbc.queryForObject("SELECT Status FROM dbo.Payments WHERE OrderId=?", String.class, orderId));

  // 3. Nếu đơn bị hủy (CANCELLED)
  jdbc.update("UPDATE dbo.Orders SET Status='CANCELLED' WHERE OrderId=?", orderId);
  var statusCancelled = checkout.checkQrStatus(1, orderId);
  assertEquals("CANCELLED", statusCancelled.get("status"));
  assertEquals(false, statusCancelled.get("shouldRedirect"));
  assertEquals(true, statusCancelled.get("isCancelled"));
 }
