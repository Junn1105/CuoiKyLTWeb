package vn.mocsach.catalog;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.jdbc.JdbcTest;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;

import java.time.Instant;

import static org.junit.jupiter.api.Assertions.*;

@JdbcTest
@Import(NotificationService.class)
class NotificationServiceTest {
 @Autowired JdbcTemplate jdbc;
 @Autowired NotificationService notifications;

 @BeforeEach void setup(){
  jdbc.execute("CREATE SCHEMA IF NOT EXISTS dbo");
  jdbc.execute("""
   CREATE TABLE IF NOT EXISTS dbo.Notifications(
    NotificationId bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UserId int NOT NULL,
    StoreId int NULL,
    Type varchar(30) NOT NULL,
    Title nvarchar(255) NOT NULL,
    Content nvarchar(2000) NOT NULL,
    TargetUrl nvarchar(255) NULL,
    CreatedAt timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ReadAt timestamp NULL
   )
   """);
  jdbc.update("DELETE FROM dbo.Notifications");
 }

 @Test void createsListsOpensAndMarksNotificationsAsRead(){
  notifications.create(1,"CART","Giỏ hàng","Đã thêm Truyện Kiều vào giỏ hàng.","/cart");
  notifications.create(1,"REVIEW","Đánh giá sách","Cảm ơn bạn đã gửi nhận xét.","/books/1#reviews");
  notifications.create(2,"SYSTEM","Hệ thống","Chào mừng bạn đọc khác.","/home");

  assertEquals(2,notifications.unreadCount(1));
  var list=notifications.list(1,10);
  assertEquals(2,list.size());

  var first=list.get(0);
  long firstId=((Number)first.get("id")).longValue();
  assertTrue((Boolean)first.get("unread"));

  String target=notifications.openAndMarkRead(1,firstId);
  assertTrue(target.startsWith("/"));
  assertEquals(1,notifications.unreadCount(1));

  notifications.markAllRead(1);
  assertEquals(0,notifications.unreadCount(1));
  assertEquals(1,notifications.unreadCount(2));
 }

 @Test void sanitizesTargetUrlsAndFormatsRelativeTime(){
  assertEquals("/books/10#reviews",NotificationService.safeTargetUrl("/books/10#reviews"));
  assertEquals("/notifications",NotificationService.safeTargetUrl("/account/notifications"));
  assertEquals("/notifications",NotificationService.safeTargetUrl("https://evil.example/phish"));
  assertEquals("🛒",NotificationService.iconFor("CART"));
  assertEquals("★",NotificationService.iconFor("REVIEW"));
  Instant now=Instant.now();
  assertEquals("Vừa xong",NotificationService.relativeTime(now.minusSeconds(15),now));
  assertEquals("2 giờ trước",NotificationService.relativeTime(now.minusSeconds(7200),now));
 }
}
