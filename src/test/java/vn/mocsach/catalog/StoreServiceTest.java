 @Test
 void testStaffAssignmentLifecycle() {
  storeService.assignStaff(2, 1, "MANAGER");
  var list = storeService.listStaffAssignments();
  assertEquals(1, list.size());
  assertEquals("MANAGER", list.get(0).get("storeRole"));
  assertEquals("ACTIVE", list.get(0).get("status"));

  int assignmentId = ((Number) list.get(0).get("assignmentId")).intValue();
  storeService.endStaffAssignment(assignmentId);

  var listAfter = storeService.listStaffAssignments();
  assertEquals("ENDED", listAfter.get(0).get("status"));
 }

 @Test
 void testFullStockTransferLifecycle() {
  // 1. Tạo phiếu DRAFT chuyển 2 cuốn từ store 1 sang store 2
  int transferId = storeService.createStockTransfer(1, 2, List.of(1, 2), 2, "Chuyển sách bổ sung kho");
  assertTrue(transferId > 0);

  var detail = storeService.getTransferDetail(transferId);
  assertEquals("DRAFT", detail.get("status"));
  assertEquals(2, ((List<?>) detail.get("items")).size());

  // 2. Phê duyệt phiếu (APPROVED) - Chỉ admin mới được duyệt
  storeService.approveStockTransfer(transferId, 1);
  var approved = storeService.getTransferDetail(transferId);
  assertEquals("APPROVED", approved.get("status"));

  // 3. Xuất kho (SHIP) -> Sách chuyển sang trạng thái IN_TRANSIT
  storeService.shipStockTransfer(transferId);
  var shipped = storeService.getTransferDetail(transferId);
  assertEquals("IN_TRANSIT", shipped.get("status"));

  String copyStatus = jdbc.queryForObject("SELECT Status FROM dbo.BookCopies WHERE CopyId = 1", String.class);
  assertEquals("IN_TRANSIT", copyStatus);

  // 4. Nhận hàng tại chi nhánh đích (RECEIVE) -> Sách chuyển sang StoreId=2 và Status='AVAILABLE'
  storeService.receiveStockTransfer(transferId);
  var received = storeService.getTransferDetail(transferId);
  assertEquals("RECEIVED", received.get("status"));

  var copy1 = jdbc.queryForMap("SELECT StoreId, Status FROM dbo.BookCopies WHERE CopyId = 1");
  assertEquals(2, ((Number) copy1.get("StoreId")).intValue());
  assertEquals("AVAILABLE", copy1.get("Status"));

  var copy2 = jdbc.queryForMap("SELECT StoreId, Status FROM dbo.BookCopies WHERE CopyId = 2");
  assertEquals(2, ((Number) copy2.get("StoreId")).intValue());
  assertEquals("AVAILABLE", copy2.get("Status"));
 }

 @Test
 void testCancelStockTransferRestoresCopies() {
  int transferId = storeService.createStockTransfer(1, 2, List.of(1), 2, "Test cancel");
  storeService.approveStockTransfer(transferId, 1);
  storeService.shipStockTransfer(transferId);

  // Lúc này sách đang IN_TRANSIT
  assertEquals("IN_TRANSIT", jdbc.queryForObject("SELECT Status FROM dbo.BookCopies WHERE CopyId = 1", String.class));

  // Hủy phiếu -> sách phải tự phục hồi về AVAILABLE tại store 1
  storeService.cancelStockTransfer(transferId);
  var copy1 = jdbc.queryForMap("SELECT StoreId, Status FROM dbo.BookCopies WHERE CopyId = 1");
  assertEquals(1, ((Number) copy1.get("StoreId")).intValue());
  assertEquals("AVAILABLE", copy1.get("Status"));
 }

