package vn.mocsach.catalog;

import org.junit.jupiter.api.*;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.jdbc.JdbcTest;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.mock.web.MockHttpServletRequest;
import org.springframework.web.server.ResponseStatusException;
import vn.mocsach.auth.AuthProblem;
import java.math.BigDecimal;
import java.util.List;
import java.util.Map;
import static org.junit.jupiter.api.Assertions.*;

@JdbcTest
@Import({CatalogService.class,CartService.class})
class CartServiceTest {
 @Autowired JdbcTemplate jdbc;
 @Autowired CartService cart;

 @BeforeEach void setup(){
  jdbc.execute("CREATE SCHEMA IF NOT EXISTS dbo");
  for(String sql:new String[]{
   "CREATE TABLE dbo.Categories(CategoryId int,CategoryName nvarchar(100))",
   "CREATE TABLE dbo.Books(BookId int,Title nvarchar(255),CoverImage nvarchar(255),CategoryId int)",
   "CREATE TABLE dbo.Authors(AuthorId int,AuthorName nvarchar(150))",
   "CREATE TABLE dbo.BookAuthors(BookId int,AuthorId int)",
   "CREATE TABLE dbo.Users(UserId int,FullName nvarchar(150),Status varchar(20))",
   "CREATE TABLE dbo.Stores(StoreId int,StoreName nvarchar(150),Status varchar(20))",
   "CREATE TABLE dbo.BookConditions(ConditionId int,ConditionName nvarchar(100))",
   "CREATE TABLE dbo.BookCopies(CopyId int,CopyCode varchar(50),BookId int,StoreId int,ConditionId int,Status varchar(20),SalePrice decimal(19,2),ConditionNotes nvarchar(1000))",
   "CREATE TABLE dbo.Carts(CartId int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,UserId int,StoreId int,Status varchar(20),CreatedAt timestamp,UpdatedAt timestamp)",
   "CREATE TABLE dbo.CartItems(CartItemId int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,CartId int,CopyId int,AddedAt timestamp,UNIQUE(CartId,CopyId))"
  })jdbc.execute(sql.replace("CREATE TABLE ","CREATE TABLE IF NOT EXISTS "));
  for(String name:new String[]{"CartItems","Carts","BookCopies","BookConditions","Stores","BookAuthors","Authors","Books","Categories","Users"})
   jdbc.update("DELETE FROM dbo."+name);
  jdbc.update("INSERT INTO dbo.Categories VALUES(1,'Văn học')");
  jdbc.update("INSERT INTO dbo.Books VALUES(1,'Truyện Kiều','/images/books/truyen-kieu.jpg',1),(2,'Số Đỏ',NULL,1)");
  jdbc.update("INSERT INTO dbo.Authors VALUES(1,'Nguyễn Du')");
  jdbc.update("INSERT INTO dbo.BookAuthors VALUES(1,1)");
  jdbc.update("INSERT INTO dbo.Users VALUES(1,'Nguyễn Khang','ACTIVE'),(2,'Hoàng Văn','ACTIVE'),(3,'Bị khóa','LOCKED')");
  jdbc.update("INSERT INTO dbo.Stores VALUES(1,'Chi nhánh Quận 1','ACTIVE'),(2,'Chi nhánh Quận 3','ACTIVE'),(3,'Chi nhánh Tạm nghỉ','TEMPORARILY_CLOSED')");
  jdbc.update("INSERT INTO dbo.BookConditions VALUES(1,'Như mới'),(2,'Tốt')");
  jdbc.update("""
   INSERT INTO dbo.BookCopies(CopyId,CopyCode,BookId,StoreId,ConditionId,Status,SalePrice,ConditionNotes) VALUES
   (10,'C1-010',1,1,2,'AVAILABLE',65000,'Bìa đẹp'),
   (11,'C2-011',1,2,1,'AVAILABLE',55000,'Rất mới'),
   (12,'C1-012',1,1,1,'SOLD',45000,NULL),
   (13,'C3-013',1,3,1,'AVAILABLE',40000,'Chi nhánh tạm nghỉ')
   """);
 }

 @Test void picksCheapestAvailableCopiesFromActiveStoresAndSplitsByStoreCart(){
  int added=cart.add(1,1,2);
  assertEquals(2,added);
  assertEquals(2,cart.count(1));
  assertEquals(2,cart.bookCountInCart(1,1));
  var detail=cart.detail(1);
  assertEquals(2,detail.get("totalCount"));
  assertEquals(2,detail.get("availableCount"));
  assertEquals(0,detail.get("unavailableCount"));
  assertEquals(2,detail.get("storeCount"));
  assertEquals(0,new BigDecimal("120000").compareTo((BigDecimal)detail.get("subtotal")));
  assertThrows(AuthProblem.class,()->cart.add(1,1,1));
 }

 @Test void flagsCopyThatBecomesSoldAfterBeingAddedToCart(){
  cart.add(1,1,2);
  jdbc.update("UPDATE dbo.BookCopies SET Status='SOLD' WHERE CopyId=11");
  var detail=cart.detail(1);
  assertEquals(2,detail.get("totalCount"));
  assertEquals(1,detail.get("availableCount"));
  assertEquals(1,detail.get("unavailableCount"));
  assertEquals(0,new BigDecimal("65000").compareTo((BigDecimal)detail.get("subtotal")));
 }

 @Test void removeItemAndClearOnlyAffectOwnerActiveCart(){
  cart.add(1,1,2);
  cart.add(2,1,1);
  @SuppressWarnings("unchecked")
  var items=(List<Map<String,Object>>)cart.detail(1).get("items");
  int firstItemId=((Number)items.get(0).get("cartItemId")).intValue();
  assertThrows(AuthProblem.class,()->cart.removeItem(2,firstItemId));
  cart.removeItem(1,firstItemId);
  assertEquals(1,cart.count(1));
  assertEquals(1,cart.count(2));
  cart.clear(1);
  assertEquals(0,cart.count(1));
  assertEquals(1,cart.count(2));
 }

 @Test void rejectsInvalidQuantityLockedUserMissingBookAndOutOfStockBook(){
  assertThrows(AuthProblem.class,()->cart.add(1,1,0));
  assertThrows(AuthProblem.class,()->cart.add(1,1,3));
  assertThrows(AuthProblem.class,()->cart.add(3,1,1));
  assertThrows(AuthProblem.class,()->cart.add(1,2,1));
  assertThrows(ResponseStatusException.class,()->cart.add(1,999,1));
 }

 @Test void safeTargetPreventsExternalRedirects(){
  var req=new MockHttpServletRequest();
  req.addHeader("Referer","http://localhost:8080/home?category=1&q=kieu");
  assertEquals("/home?category=1&q=kieu",CartController.safeTarget("",req,5));
  assertEquals("/books/5",CartController.safeTarget("https://evil.example/phish",new MockHttpServletRequest(),5));
  assertEquals("/books/5",CartController.safeTarget("//evil.example",new MockHttpServletRequest(),5));
  assertEquals("/books/5",CartController.safeTarget("/books/5",new MockHttpServletRequest(),5));
 }
}
