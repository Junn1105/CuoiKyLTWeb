package vn.mocsach.catalog;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.jdbc.JdbcTest;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;

import java.math.BigDecimal;

import static org.junit.jupiter.api.Assertions.*;

@JdbcTest
@Import({CatalogService.class, NotificationService.class, AdminService.class})
class AdminServiceTest {
 @Autowired JdbcTemplate jdbc;
 @Autowired AdminService admin;
 @Autowired NotificationService notifications;

 @BeforeEach void setup() {
  jdbc.execute("CREATE SCHEMA IF NOT EXISTS dbo");
  for (String sql : new String[]{
   "CREATE TABLE dbo.Roles(RoleId int PRIMARY KEY,RoleCode varchar(50),RoleName nvarchar(100))",
   "CREATE TABLE dbo.UserRoles(UserId int,RoleId int,PRIMARY KEY(UserId,RoleId))",
   "CREATE TABLE dbo.Categories(CategoryId int PRIMARY KEY,CategoryName nvarchar(100),Slug varchar(120))",
   "CREATE TABLE dbo.Publishers(PublisherId int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,PublisherName nvarchar(150))",
   "CREATE TABLE dbo.Authors(AuthorId int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,AuthorName nvarchar(150))",
   "CREATE TABLE dbo.Books(BookId int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,ISBN varchar(20),Title nvarchar(255),CategoryId int,PublisherId int,PublishYear int,CoverImage nvarchar(255),Description nvarchar(1000),Translator nvarchar(150))",
   "CREATE TABLE dbo.BookAuthors(BookId int,AuthorId int,PRIMARY KEY(BookId,AuthorId))",
   "CREATE TABLE dbo.BookReviews(ReviewId int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,BookId int,UserId int,Rating int,CommentText nvarchar(1000))",
   "CREATE TABLE dbo.Stores(StoreId int PRIMARY KEY,StoreCode varchar(20),StoreName nvarchar(150),Status varchar(20))",
   "CREATE TABLE dbo.BookConditions(ConditionId int PRIMARY KEY,ConditionCode varchar(30),ConditionName nvarchar(100),SortOrder int)",
   "CREATE TABLE dbo.BookCopies(CopyId int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,CopyCode varchar(50),BookId int,StoreId int,ConditionId int,PurchaseReceiptItemId int,CostPrice decimal(19,2),SalePrice decimal(19,2),ConditionNotes nvarchar(1000),ShelfLocation nvarchar(100),Status varchar(20),Version bigint DEFAULT 0,CreatedAt timestamp,UpdatedAt timestamp)",
   "CREATE TABLE dbo.CartItems(CartItemId int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,CartId int,CopyId int)",
   "CREATE TABLE dbo.Orders(OrderId int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,OrderCode varchar(40),StoreId int,CustomerId int,Status varchar(20),RecipientName nvarchar(150),RecipientPhone varchar(20),ShippingAddressSnapshot nvarchar(1000),Subtotal decimal(19,2),ShippingFee decimal(19,2),TotalAmount decimal(19,2),Version bigint DEFAULT 0,CreatedAt timestamp,UpdatedAt timestamp)",
   "CREATE TABLE dbo.OrderItems(OrderItemId int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,OrderId int,CopyId int,BookTitleSnapshot nvarchar(255),ConditionSnapshot nvarchar(255),UnitPrice decimal(19,2),UnitCostSnapshot decimal(19,2),DiscountAmount decimal(19,2),LineTotal decimal(19,2))",
   "CREATE TABLE dbo.OrderStatusHistory(HistoryId bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,OrderId int,FromStatus varchar(20),ToStatus varchar(20),ChangedBy int,ChangedAt timestamp,Reason nvarchar(1000))",
   "CREATE TABLE dbo.Payments(PaymentId int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,OrderId int,Method varchar(20),Amount decimal(19,2),Status varchar(20),PaidAt timestamp,CreatedAt timestamp)",
   "CREATE TABLE dbo.Notifications(NotificationId bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,UserId int,StoreId int,Type varchar(30),Title nvarchar(255),Content nvarchar(1000),TargetUrl nvarchar(500),CreatedAt timestamp DEFAULT CURRENT_TIMESTAMP,ReadAt timestamp)"
  }) jdbc.execute(sql.replace("CREATE TABLE ", "CREATE TABLE IF NOT EXISTS "));

  for (String name : new String[]{"Notifications", "Payments", "OrderStatusHistory", "OrderItems", "Orders", "CartItems", "BookCopies", "BookConditions", "Stores", "BookReviews", "BookAuthors", "Books", "Authors", "Publishers", "Categories", "UserRoles", "Roles"})
   jdbc.update("DELETE FROM dbo." + name);

  jdbc.update("INSERT INTO dbo.Roles VALUES(1,'ADMIN','Quản trị viên'),(2,'CUSTOMER','Khách hàng'),(3,'STAFF','Nhân viên')");
  jdbc.update("INSERT INTO dbo.UserRoles VALUES(1,1),(2,3),(3,2)");
  jdbc.update("INSERT INTO dbo.Categories VALUES(1,'Văn học','van-hoc')");
  jdbc.update("INSERT INTO dbo.Stores VALUES(1,'HCM-Q3','Chi nhánh Quận 3','ACTIVE')");
  jdbc.update("INSERT INTO dbo.BookConditions VALUES(1,'LIKE_NEW','Như mới',1),(2,'GOOD','Tốt',2),(3,'FAIR','Khá',3)");
 }

 @Test void managesBookCopiesCostPriceSalePriceAndOrdersForStaffAndAdminOnly() {
  assertTrue(admin.isStaffOrAdmin(1));
  assertTrue(admin.isStaffOrAdmin(2));
  assertFalse(admin.isStaffOrAdmin(3));

  int bookId = admin.createBook(
   "Truyện Kiều Bản Cổ", 1, "Nguyễn Du", "NXB Văn Học",
   2022, "", "9786049999999", "", "Ấn bản đặc biệt",
   1, 1, new BigDecimal("35000"), new BigDecimal("65000"), 2
  );
  assertTrue(bookId > 0);

  var editView = admin.bookForEdit(bookId);
  assertEquals("Truyện Kiều Bản Cổ", editView.get("title"));
  assertEquals("Nguyễn Du", editView.get("authors"));

  var copies = admin.bookCopiesForStaff(bookId);
  assertEquals(2, copies.size());
  int firstCopyId = (Integer) copies.get(0).get("copyId");
  assertEquals(0, new BigDecimal("35000").compareTo((BigDecimal) copies.get(0).get("costPrice")));
  assertEquals(0, new BigDecimal("65000").compareTo((BigDecimal) copies.get(0).get("salePrice")));

  admin.updateCopy(firstCopyId, 1, 2, new BigDecimal("32000"), new BigDecimal("58000"), "AVAILABLE", "Bìa tốt");
  var updatedCopies = admin.bookCopiesForStaff(bookId);
  assertEquals("Tốt", updatedCopies.get(0).get("conditionName"));
  assertEquals(0, new BigDecimal("32000").compareTo((BigDecimal) updatedCopies.get(0).get("costPrice")));
  assertEquals(0, new BigDecimal("58000").compareTo((BigDecimal) updatedCopies.get(0).get("salePrice")));

  admin.updateBook(bookId, "Truyện Kiều (Tái Bản)", 1, "Nguyễn Du", "NXB Văn Học", 2024, "", "9786049999999", "", "Bản mới");
  assertEquals("Truyện Kiều (Tái Bản)", admin.bookForEdit(bookId).get("title"));

  jdbc.update("""
   INSERT INTO dbo.Orders(OrderId,OrderCode,StoreId,CustomerId,Status,RecipientName,RecipientPhone,ShippingAddressSnapshot,Subtotal,ShippingFee,TotalAmount,Version,CreatedAt,UpdatedAt)
   VALUES(100,'MS-TEST-100',1,3,'PENDING','Khách Hàng','0909111222','Quận 1',58000,25000,83000,0,CURRENT_TIMESTAMP,CURRENT_TIMESTAMP)
   """);
  jdbc.update("""
   INSERT INTO dbo.OrderItems(OrderId,CopyId,BookTitleSnapshot,ConditionSnapshot,UnitPrice,UnitCostSnapshot,DiscountAmount,LineTotal)
   VALUES(100,?,'Truyện Kiều (Tái Bản)','Tốt',58000,32000,0,58000)
   """, firstCopyId);
  jdbc.update("INSERT INTO dbo.Payments(OrderId,Method,Amount,Status,CreatedAt) VALUES(100,'CASH',83000,'PENDING',CURRENT_TIMESTAMP)");

  var stats = admin.dashboardStats();
  assertEquals(1, stats.get("totalBooks"));
  assertEquals(1, stats.get("totalOrders"));

  admin.updateOrderStatus(2, 100, "COMPLETED");
  assertEquals("COMPLETED", admin.listAllOrders("COMPLETED").get(0).get("status"));
  assertEquals("SOLD", jdbc.queryForObject("SELECT Status FROM dbo.BookCopies WHERE CopyId=?", String.class, firstCopyId));
  assertTrue(notifications.unreadCount(3) > 0);

  admin.deleteBook(bookId);
  assertEquals(0, admin.dashboardStats().get("totalBooks"));
 }
}
