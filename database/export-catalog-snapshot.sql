SET NOCOUNT ON;
SELECT
 (SELECT * FROM dbo.Books ORDER BY BookId FOR JSON PATH, INCLUDE_NULL_VALUES) AS Books,
 (SELECT * FROM dbo.Authors ORDER BY AuthorId FOR JSON PATH, INCLUDE_NULL_VALUES) AS Authors,
 (SELECT * FROM dbo.Categories ORDER BY CategoryId FOR JSON PATH, INCLUDE_NULL_VALUES) AS Categories,
 (SELECT * FROM dbo.Publishers ORDER BY PublisherId FOR JSON PATH, INCLUDE_NULL_VALUES) AS Publishers,
 (SELECT * FROM dbo.BookAuthors ORDER BY BookId, AuthorId FOR JSON PATH, INCLUDE_NULL_VALUES) AS BookAuthors
FOR JSON PATH, WITHOUT_ARRAY_WRAPPER;
